/**
 * Numeric id → canonical command name, the inversion of {@link CommandType}.
 *
 * Five ids carry two names in the enum — 1040 is both `CMD_DEVS_UNBIND` and `P2P_RESET`, 1238 both
 * `CMD_SET_UPGRADE` and `P2P_ENTER_OTA`, 2107/2109 both `CMD_SMART_DROP_*` and `SUB1G_REP_*`, and
 * 1946165248 both `CMD_SMARTSAFE_IS_ENABLE_BEEP` and `CMD_SMARTSAFE_PARAM_BASE`. The later
 * declaration is the label.
 */
const COMMAND_NAMES: Readonly<Record<number, string>> = enumLabels(CommandType);

/** Resolve a command id to a name, falling back to `CMD_<id>` for unknowns. */
export function commandName(id: number): string {
  return COMMAND_NAMES[id] ?? `CMD_${id}`;
}
